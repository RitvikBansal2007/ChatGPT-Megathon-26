"""Receipts — model evaluation, LLM eval, scenario suite results.

For auditors and evaluators. All data from client.get_eval().
Nothing hard-coded — every number from the API/fixture.
"""

import streamlit as st
import plotly.graph_objects as go
import pandas as pd

import theme
import client
from components.chrome import banner, current_role

st.set_page_config(page_title="GreenProof – Receipts", layout="wide")
st.markdown(theme.css(), unsafe_allow_html=True)

banner()
st.title("Receipts")
role = current_role()
st.caption(f"Viewing as: {role}")

with st.spinner("Loading evaluation results…"):
    try:
        ev = client.get_eval()
    except Exception as exc:
        st.error(f"Could not load evaluation data: {exc}", icon=":material/error:")
        st.stop()

as_of = ev.get("as_of", "—")
st.caption(f"Evaluation as of {as_of} · Synthetic data · Generated by `make eval`")

# ── 1. Lift vs baselines ──────────────────────────────────────────────────────
st.subheader("Model lift vs baselines")
baselines = ev.get("baselines", {})
if baselines:
    rows = []
    for pid, b in baselines.items():
        rows.append({
            "Product": pid,
            "LightGBM AUC": b.get("lgbm_auc", "—"),
            "Logistic Regression AUC": b.get("lr_auc", "—"),
            "Rule Heuristic AUC": b.get("rule_auc", "—"),
            "Lift top-10%": b.get("lgbm_lift_top10", "—"),
        })
    st.dataframe(pd.DataFrame(rows).set_index("Product"), use_container_width=True)

st.divider()

# ── 2. Calibration curve ──────────────────────────────────────────────────────
col_cal, col_brier = st.columns(2, gap="medium")
with col_cal:
    st.subheader("Calibration curve")
    cal = ev.get("calibration", [])
    if cal:
        fig = go.Figure()
        fig.add_trace(go.Scatter(
            x=[r["mean_pred"] for r in cal],
            y=[r["mean_actual"] for r in cal],
            mode="lines+markers",
            name="Model",
            line=dict(color=theme.METRICS["CO2E"]["chart"], width=2),
            marker=dict(size=8),
        ))
        fig.add_trace(go.Scatter(
            x=[0, 1], y=[0, 1], mode="lines", name="Perfect",
            line=dict(color="#6B8A7C", dash="dot", width=1),
        ))
        fig.update_layout(
            paper_bgcolor="rgba(0,0,0,0)", plot_bgcolor="rgba(241,248,244,0.5)",
            xaxis_title="Mean predicted probability",
            yaxis_title="Mean actual take-up rate",
            font_family="Inter, system-ui, sans-serif",
            margin=dict(l=0, r=0, t=0, b=0),
            height=280, showlegend=True,
        )
        st.plotly_chart(fig, use_container_width=True, config={"displayModeBar": False})

with col_brier:
    st.subheader("Brier score by confidence tercile")
    brier = ev.get("brier_by_tercile", {})
    if brier:
        fig2 = go.Figure(go.Bar(
            x=list(brier.keys()), y=list(brier.values()),
            marker_color=[theme.METRICS["CO2E"]["chart"], theme.METRICS["ENERGY"]["chart"], theme.METRICS["PAPER"]["chart"]],
        ))
        fig2.update_layout(
            paper_bgcolor="rgba(0,0,0,0)", plot_bgcolor="rgba(241,248,244,0.5)",
            xaxis_title="Confidence tercile", yaxis_title="Brier score (lower = better)",
            font_family="Inter, system-ui, sans-serif",
            margin=dict(l=0, r=0, t=0, b=0), height=280,
        )
        st.plotly_chart(fig2, use_container_width=True, config={"displayModeBar": False})

st.divider()

# ── 3. Categoriser ────────────────────────────────────────────────────────────
cat = ev.get("categoriser", {})
col_cat1, col_cat2 = st.columns(2)
with col_cat1:
    st.metric("Categoriser macro-F1", f"{cat.get('macro_f1', 0):.3f}", help="On unseen merchants vs rules-only baseline")
with col_cat2:
    st.metric("Rules-only macro-F1", f"{cat.get('rules_only_f1', 0):.3f}", help="Baseline")

st.divider()

# ── 4. LLM eval table ────────────────────────────────────────────────────────
st.subheader("LLM evaluation: governed vs naive prompt")
llm = ev.get("llm_eval", {})
if llm:
    llm_rows = []
    for mode, vals in llm.items():
        llm_rows.append({
            "Prompt":               mode.capitalize(),
            "Numeric fidelity":     f"{vals.get('numeric_fidelity',0):.0%}",
            "Unsupported claim rate":f"{vals.get('unsupported_claim_rate',0):.0%}",
            "Banned phrase rate":   f"{vals.get('banned_phrase_rate',0):.0%}",
            "Fallback rate":        f"{vals.get('fallback_rate',0):.0%}",
            "p50 latency (ms)":     vals.get("p50_latency_ms", "—"),
            "Cost / 1,000 (£)":     f"£{vals.get('cost_per_1000',0):.2f}",
        })
    st.dataframe(pd.DataFrame(llm_rows).set_index("Prompt"), use_container_width=True)

st.divider()

# ── 5. Scenario suite pass/fail ───────────────────────────────────────────────
st.subheader("Scenario suite")
sc = ev.get("scenarios", {})
passed = sc.get("passed", 0)
total = sc.get("total", 0)
failures = sc.get("failures", [])
if passed == total:
    st.success(f"✓ {passed}/{total} scenarios passed", icon=":material/check_circle:")
else:
    st.warning(f"⚠ {passed}/{total} scenarios passed", icon=":material/warning:")
if failures:
    with st.expander(f"{len(failures)} failure(s)", expanded=False):
        for f in failures:
            st.markdown(f"- `{f}`")

st.caption("Not a credit decision. All figures are from synthetic data.")
