import json
import os

def generate_report():
    out_dir = os.path.join(os.path.dirname(__file__), '../out')
    fixtures_dir = os.path.join(os.path.dirname(__file__), '../fixtures')
    
    os.makedirs(out_dir, exist_ok=True)
    
    eval_path = os.path.join(out_dir, 'eval_summary.json')
    if not os.path.exists(eval_path):
        eval_path = os.path.join(fixtures_dir, 'eval.json')
    with open(eval_path, 'r') as f:
        metrics = json.load(f)
        
    baselines = metrics.get('baselines', {})
    cat = metrics.get('categoriser', {})
    scen = metrics.get('scenarios', {})
    llm = metrics.get('llm_eval', {})
    split = metrics.get('split', {})

    def row(pid, name):
        b = baselines.get(pid, {})
        return (f"| {pid} {name} | {b.get('lgbm_auc')} | {b.get('lr_auc')} | {b.get('rule_auc')} | "
                f"{b.get('lgbm_pr_auc')} | {b.get('lgbm_brier')} | {b.get('lgbm_lift_top10')}x | {b.get('base_rate')} |")

    report_md = f"""# GreenDash Evaluation Report

Generated by `python -m greendash.models.evaluate_models` from `out/eval_summary.json`. All data is synthetic.

## Propensity models (held-out test set)

Split by customer, seed 42: {split.get('train')} train, {split.get('val')} validation, {split.get('test')} test (`data/splits/splits.json`).
Models are trained on train, early-stopped and calibrated on validation, and scored once on test.

| Product | LightGBM AUC | Logistic regression AUC | Rule AUC | LightGBM PR-AUC | LightGBM Brier | LightGBM lift at top 10% | Base rate |
|---|---|---|---|---|---|---|---|
{row('GP01', 'EV Finance')}
{row('GP02', 'Green Home')}
{row('GP03', 'Solar')}
{row('GP04', 'Paperless')}

Take-up is rare (see base rate), so each test set holds only a few dozen positives and AUC differences of a few points are within noise.

## Categoriser

* Macro-F1 on unseen merchants (5-fold GroupKFold): {cat.get('macro_f1')} (rules only: {cat.get('rules_only_f1')})

## Scenario suite

* {scen.get('passed')} / {scen.get('total')} passed. Failures: {", ".join(scen.get('failures', [])) or "none"}

## Explanations

* Packs judged: {llm.get('evaluated')}
* Served by the template fallback (no LLM call): {llm.get('template_fallback_rate')}
* Faithfulness: {llm.get('faithfulness')} | Canary leakage: {llm.get('canary_leakage_rate')}

A fallback rate of 1.0 means the run had no LLM key, so these figures describe the template path only.
"""

    docs_dir = os.path.join(os.path.dirname(__file__), '../docs')
    os.makedirs(docs_dir, exist_ok=True)
    report_path = os.path.join(docs_dir, 'EVALUATION.md')
    with open(report_path, 'w') as f:
        f.write(report_md)
        
    print(f"Report successfully generated at: {report_path}")

if __name__ == "__main__":
    generate_report()
